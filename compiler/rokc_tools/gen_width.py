#!/usr/bin/env python3
"""Generate compiler/rokc_tools/src/line_edit/width_table.rs (REPL line
editor: terminal columns per char).

Reads the UCD files checked in under `compiler/rokc_lexer/ucd/` (shared
with the lexer's `gen_unicode.py`), so regeneration is offline:
- EastAsianWidth.txt: W / F are two columns, as are the unlisted code
  points its header gives W
- emoji-data.txt: Emoji_Presentation, two columns
- UnicodeData.txt: Mn / Me / Cf are zero columns
- PropList.txt: Prepended_Concatenation_Mark (Cf, but visible)

Usage: python3 compiler/rokc_tools/gen_width.py
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
UCD = os.path.join(HERE, "..", "rokc_lexer", "ucd")
OUT = os.path.join(HERE, "src", "line_edit", "width_table.rs")


def read(name):
    with open(os.path.join(UCD, name), encoding="utf-8") as f:
        return f.read()


def ucd_prop(text, names):
    cps = set()
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        rng, prop = (s.strip() for s in line.split(";")[:2])
        if prop not in names:
            continue
        lo, _, hi = rng.partition("..")
        cps.update(range(int(lo, 16), int(hi or lo, 16) + 1))
    return cps


def ranges(cps):
    out = []
    for c in sorted(cps):
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def rows(items, per=6):
    items = list(items)
    return "".join(
        "    " + " ".join(items[i : i + per]) + "\n" for i in range(0, len(items), per)
    )


def fmt_ranges(name, cps):
    body = rows(f"(0x{lo:X}, 0x{hi:X})," for lo, hi in ranges(cps))
    return f"pub static {name}: &[(u32, u32)] = &[\n{body}];\n\n"


eaw = read("EastAsianWidth.txt")
VER = re.search(r"EastAsianWidth-([0-9.]+)\.txt", eaw).group(1)
emoji = read("emoji-data.txt")
proplist = read("PropList.txt")
assert VER in proplist.splitlines()[0], "UCD files from different versions"
assert f"Version: {VER}" in emoji, "emoji-data.txt version mismatch"

listed = set()
for line in eaw.splitlines():
    line = line.split("#", 1)[0].strip()
    if line:
        lo, _, hi = line.split(";")[0].strip().partition("..")
        listed.update(range(int(lo, 16), int(hi or lo, 16) + 1))
wide = ucd_prop(eaw, {"W", "F"})
for lo, hi in [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF),
               (0x20000, 0x2FFFD), (0x30000, 0x3FFFD)]:
    wide.update(c for c in range(lo, hi + 1) if c not in listed)
wide |= ucd_prop(emoji, {"Emoji_Presentation"})

zero = set()
for line in read("UnicodeData.txt").splitlines():
    f = line.split(";")
    if f[2] in ("Mn", "Me", "Cf"):
        zero.add(int(f[0], 16))
zero -= ucd_prop(proplist, {"Prepended_Concatenation_Mark"})
zero.discard(0xAD)
# Conjoining Hangul vowels and finals join the syllable's leading consonant.
zero.update(range(0x1160, 0x1200))
zero.update(range(0xD7B0, 0xD800))
wide -= zero
assert wide and zero

out = [
    f"//! Generated by `compiler/rokc_tools/gen_width.py` from UCD {VER}.\n",
    "//! Do not edit by hand.\n\n",
    "#![allow(clippy::unreadable_literal)]\n\n",
    fmt_ranges("ZERO", zero),
    fmt_ranges("WIDE", wide).rstrip("\n") + "\n",
]
with open(OUT, "w") as f:
    f.write("".join(out))
print(f"wrote {OUT} (UCD {VER})", file=sys.stderr)
